pub struct Table {
    pub code_of: HashMap<char, u8>,
    pub advance_of: HashMap<u8, u32>,
}

fn alias_target(c: char) -> Option<char> {
    let (from, to) = ("АВЕКМНОРСТХаеорсухЁёІіЇї", "ABEKMHOPCTXaeopcyxËëIiÏï");
    from.chars().position(|f| f == c).map(|at| to.chars().nth(at).unwrap())
}

fn existing_code(c: char) -> u8 {
    if let Some(&code) = latin::table().code_of.get(&c) {
        return code;
    }
    match c {
        'A'..='Z' => 0x10 + (c as u8 - b'A'),
        'a'..='z' => 0x30 + (c as u8 - b'a'),
        _ => unreachable!("every Cyrillic alias names a Latin glyph"),
    }
}

fn build() -> Table {
    let (mut code_of, mut advance_of) = (HashMap::new(), HashMap::new());
    let mut next = FIRST_CODE;
    for set in [RUSSIAN, UKRAINIAN_EXTRA, BELARUSIAN_EXTRA] {
        for c in set.chars().chain(set.to_lowercase().chars()) {
            if let Some(target) = alias_target(c) {
                code_of.insert(c, existing_code(target));
                continue;
            }
            let pattern = PATTERNS.iter().find(|(ch, _)| *ch == c).expect("authored Cyrillic glyph").1;
            // Each pattern's first column is cell column 1.
            let right = pattern.split('/').filter_map(|line| line.rfind('#')).max().unwrap_or(0) as u32 + 1;
            code_of.insert(c, next);
            advance_of.insert(next, right + 2);
            next += 1;
        }
    }
    Table { code_of, advance_of }
}

pub fn table() -> &'static Table {
    static TABLE: OnceLock<Table> = OnceLock::new();
    TABLE.get_or_init(build)
}
