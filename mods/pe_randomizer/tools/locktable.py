"""Story gates: every lock (a key's item-count test, op 168) with the story bit its key's vanilla spot sets,
written as pe_rand_locks.h. The mod answers "not held" at a lock until that bit is set, so a key placed
early only works once the story reaches the point where vanilla hands it out.
Usage: python -I locktable.py <randomizer-spots.txt> <story-graph.txt> <pe_rand_spots.h> > ../pe_rand_locks.h
       (the rooms ctest writes the spots file's keytest lines; storygraph.py the graph)

A spot's bit: the first story write after its give in the same routine (KEY_BIT_RANGE, as storywalk's key
bits: M114 V0x2d|0x800), else the bit the give tests clear and the room sets (a pickup sets its bit
before the give: M064 V0x36|0x2). Every give of a spot must give one bit, and no other step may set it
(writes with = are the new-game resets in M431): otherwise the key gets no gate and the script says why.
M329 sets V0x41|0x1 (St. Francis) unconditionally; that key has no item test, so it needs no gate."""
import collections, os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from keyscan import KEYS
from storywalk import KEY_BIT_RANGE

CLEAR = re.compile(r"!\(V(0x[0-9a-f]+) & (0x[0-9a-f]+)\)")


def key_spots(path):
    """{vanilla item: spot} for the table's key spots."""
    out = {}
    for line in open(path):
        m = re.match(r"\s*\{ (0x[0-9A-F]+), PE_RAND_\w+, \d+, \d+, PE_RAND_KEY,.*/\* (\d+):", line)
        if m: out[int(m.group(1), 16)] = int(m.group(2))
    return out


def read_graph(path):
    """{room: [(block at, entity, spot, ways)]} gives and {room: [(block at, entity, var, kind, n)]} writes."""
    gives, writes = collections.defaultdict(list), collections.defaultdict(list)
    for line in open(path):
        f = line.rstrip("\n").split("\t")
        if f[0] == "give" and f[5].startswith("spot="):
            gives[f[1]].append((int(f[2][1:], 16), f[3], int(f[5].split()[0][5:]), f[6]))
        elif f[0] == "write":
            writes[f[1]].append((int(f[2][1:], 16), f[3], int(f[4][1:], 16), f[5][0], int(f[5][1:], 16) & 0xFFFFFFFF))
    for w in writes.values(): w.sort()
    return gives, writes


def own_bit(room, at, ent, ways, writes):
    after = [w for w in writes[room] if at < w[0] <= at + KEY_BIT_RANGE and w[1] == ent]
    if after and after[0][3] == "|" and bin(after[0][4]).count("1") == 1: return after[0][2], after[0][4], after[0][0]
    sets = {(w[2], w[4]): w[0] for w in writes[room] if w[3] == "|"}
    for var, bit in CLEAR.findall(ways):
        if (int(var, 16), int(bit, 16)) in sets: return int(var, 16), int(bit, 16), sets[(int(var, 16), int(bit, 16))]
    return None


def main():
    if len(sys.argv) != 4: sys.exit(__doc__)
    tests = [l.rstrip("\n").split("\t") for l in open(sys.argv[1]) if l.startswith("keytest\t")]
    spots = key_spots(sys.argv[3])
    gives, writes = read_graph(sys.argv[2])
    gates, notes = {}, []
    for item in sorted({int(t[5], 16) for t in tests}):
        spot = spots.get(item)
        if spot is None: notes.append(f"{KEYS[item]}: no key spot in the table"); continue
        bits, own = set(), set()
        for room, gs in gives.items():
            for at, ent, s, ways in gs:
                if s != spot: continue
                b = own_bit(room, at, ent, ways, writes)
                if not b: bits.add(None); continue
                bits.add(b[:2]); own.add((room, b[2]))
        if len(bits) != 1 or None in bits: notes.append(f"{KEYS[item]}: spot {spot} gives {bits or 'no bit'}"); continue
        var, bit = bits.pop()
        other = [f"{room}+{at:06X}" for room, ws in writes.items() for at, _, v, kind, n in ws
                 if v == var and kind == "|" and n & bit and (room, at) not in own]
        if other: notes.append(f"{KEYS[item]}: V{var:#x}|{bit:#x} also set at {', '.join(other)}"); continue
        gates[item] = (spot, var, bit, sorted(own))
    for n in notes: print("locktable:", n, file=sys.stderr)
    rows = sorted((int(t[1][1:]), int(t[2][1:], 16), int(t[5], 16)) for t in tests if int(t[5], 16) in gates)
    print("/* Generated by mods/pe_randomizer/tools/locktable.py from the rooms ctest's keytest lines and")
    print(" * story-graph.txt - do not edit. Each lock: a key's item-count step (map, offset in the room data),")
    print(" * the key, and the story bit (V var | bit) its vanilla spot sets: the key opens it only once that's set. */")
    print("#pragma once")
    print('#include "pe_randomizer.h"')
    print()
    print(f"#define PE_RAND_LOCKS {len(rows)}")
    print("/* Sorted by map, then offset. */")
    print("static const PeRandLock g_pe_rand_locks[PE_RAND_LOCKS] = {")
    for room, at, item in rows:
        spot, var, bit, own = gates[item]
        where = ", ".join(f"{r}+{a:06X}" for r, a in own)
        print(f"    {{ {room}, 0x{at:06X}, 0x{item:02X}, {spot}, 0x{var:02X}, 0x{bit:08X} }}, /* {KEYS[item]}: {where} */")
    print("};")


if __name__ == "__main__":
    main()
